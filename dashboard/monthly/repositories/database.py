"""PostgreSQL connection boundary for all structured application records.

Uses a private application schema through a server-only connection string.
The small SQL adapter retains existing local SQLite contracts during migration.
"""
from contextlib import contextmanager
import re
import sqlite3


class Record(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def record_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: Record(zip(names, values))


def postgres_sql(statement):
    statement = statement.strip()
    if statement == 'BEGIN IMMEDIATE':
        # Serialize account-bootstrap/last-admin checks and dataset activation across workers.
        return 'SELECT pg_advisory_xact_lock(818204329)'
    ignored = statement.startswith('INSERT OR IGNORE ')
    statement = statement.replace('INSERT OR IGNORE ', 'INSERT ')
    statement = statement.replace('INTEGER PRIMARY KEY', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    statement = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', statement)
    statement = re.sub(r'\bBLOB\b', 'BYTEA', statement)
    statement = statement.replace('?', '%s')
    return statement + (' ON CONFLICT DO NOTHING' if ignored else '')


class Cursor:
    def __init__(self, cursor, lastrowid=None):
        self.cursor, self.lastrowid = cursor, lastrowid

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()

    def __iter__(self):
        return iter(self.cursor)


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, statement, parameters=()):
        import psycopg
        query = postgres_sql(statement)
        returning_id = bool(re.match(r'INSERT INTO users\s*\(', query, re.I))
        if returning_id:
            query += ' RETURNING id'
        try:
            cursor = self.connection.execute(query, parameters)
        except psycopg.IntegrityError as exc:
            raise sqlite3.IntegrityError('Database integrity constraint rejected this operation.') from exc
        return Cursor(cursor, cursor.fetchone()[0] if returning_id else None)

    def executemany(self, statement, parameters):
        for values in parameters:
            self.execute(statement, values)

    def executescript(self, script):
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)


@contextmanager
def postgres_connection(url, schema):
    import psycopg
    from psycopg import sql
    # Never silently fall back to local storage if a configured cloud connection fails.
    with psycopg.connect(url, sslmode='require', connect_timeout=15, row_factory=record_factory) as connection:
        connection.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(schema)))
        yield PostgresConnection(connection)


def initialize_schema(url, schema):
    import psycopg
    from psycopg import sql
    if not re.fullmatch(r'[a-z][a-z0-9_]{0,62}', schema) or schema == 'public':
        raise ValueError('Use a private PostgreSQL application schema, not public.')
    with psycopg.connect(url, sslmode='require', connect_timeout=15) as connection:
        connection.execute(sql.SQL('CREATE SCHEMA IF NOT EXISTS {}').format(sql.Identifier(schema)))
        connection.execute(sql.SQL('REVOKE ALL ON SCHEMA {} FROM PUBLIC').format(sql.Identifier(schema)))
